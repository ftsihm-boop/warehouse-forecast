// --- рисунки -----------------------------------------------------------------
// Схемы плотные, и на книжной странице подписи внутри блоков опускались бы
// примерно до 4,5 пункта. Поэтому они размещаются на альбомных страницах:
// ГОСТ 2.105 прямо допускает поворот рисунка, ширина которого превышает
// ширину страницы. Каждая такая страница оформляется отдельным разделом.
let figCount = 0;

function figureBlock(file, w, h, caption, dir) {
  return [
    new Paragraph({
      children: [new ImageRun({
        type: "png",
        data: fs.readFileSync(path.join(dir, file)),
        transformation: { width: w, height: h },
      })],
      alignment: AlignmentType.CENTER,
      spacing: { before: 0, after: 120 },
    }),
    new Paragraph({
      children: [run(`Рисунок 2.${figCount} — ${caption}`)],
      alignment: AlignmentType.CENTER,
      spacing: { line: LINE, after: 0 },
    }),
  ];
}

/** Рисунок на книжной странице — для скриншотов. */
function FIG(file, w, h, caption, dir = DIA) {
  figCount += 1;
  return figureBlock(file, w, h, caption, dir);
}

/** Схема на отдельной альбомной странице. */
function FIG_WIDE(file, w, h, caption, dir = DIA) {
  figCount += 1;
  flushSection();
  sections.push({ landscape: true, children: figureBlock(file, w, h, caption, dir) });
  return [];
}

// --- таблицы -----------------------------------------------------------------
let tblCount = 0;
const TOTAL_W = convertMillimetersToTwip(170);   // 210 - 30 - 10

function cell(text, widthDxa, o = {}) {
  return new TableCell({
    width: { size: widthDxa, type: WidthType.DXA },
    shading: o.head ? { type: ShadingType.CLEAR, fill: GREY, color: "auto" } : undefined,
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    children: String(text).split("\n").map((line, i) => new Paragraph({
      children: [run(line, { bold: !!o.head, size: 22 })],
      alignment: o.head ? AlignmentType.CENTER
        : (o.center ? AlignmentType.CENTER : AlignmentType.LEFT),
      spacing: { line: 240, before: i === 0 ? 0 : 0 },
    })),
  });
}

/**
 * Таблица с подписью сверху, как требует ГОСТ.
 * shares — доли ширины колонок, в сумме 1.
 */
function TBL(caption, headers, rows, shares, opts = {}) {
  tblCount += 1;
  const widths = shares.map((s) => Math.round(TOTAL_W * s));
  widths[widths.length - 1] = TOTAL_W - widths.slice(0, -1).reduce((a, b) => a + b, 0);
  const centerCols = opts.center || [];

  const table = new Table({
    width: { size: TOTAL_W, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((h, i) => cell(h, widths[i], { head: true })),
      }),
      ...rows.map((r) => new TableRow({
        children: r.map((c, i) => cell(c, widths[i], { center: centerCols.includes(i) })),
      })),
    ],
  });

  return [
    new Paragraph({
      children: [run(`Таблица 2.${tblCount} — ${caption}`)],
      spacing: { line: LINE, before: 240, after: 100 },
    }),
    table,
    new Paragraph({ children: [run("")], spacing: { line: LINE, after: 120 } }),
  ];
}

